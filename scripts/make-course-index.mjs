import { writeFile } from 'node:fs/promises';
import { courses } from '../assets/js/data/data.js';
import { writeLessonModules } from './make-lesson-data.mjs';

const summary = courses.map((course) => ({
  id: course.id,
  title: course.title,
  subtitle: course.subtitle,
  description: course.description,
  status: course.status,
  level: course.level,
  ...(course.language ? { language: course.language } : {}),
  modules: course.modules.map((module) => ({
    id: module.id,
    title: module.title,
    description: module.description,
    lessons: module.lessons.map((lesson) => ({
      id: lesson.id,
      title: lesson.title,
      minutes: lesson.minutes,
      xp: lesson.xp,
      ...(lesson.language ? { language: lesson.language } : {})
    }))
  }))
}));

const output = `// Generated by scripts/make-course-index.mjs from assets/js/data/data.js.
export const courses = ${JSON.stringify(summary, null, 2)};

export function getCourse(courseId) {
  return courses.find((course) => course.id === courseId) || null;
}

export function getAllLessons(course) {
  if (!course) return [];
  return course.modules.flatMap((module) => module.lessons);
}
`;

await writeFile(new URL('../assets/js/data/course-index.js', import.meta.url), output);
const lessonCount = summary.reduce(
  (total, course) => total + course.modules.reduce((sum, module) => sum + module.lessons.length, 0),
  0
);
console.log(`Wrote ${summary.length} courses and ${lessonCount} lesson summaries to course-index.js`);
await writeLessonModules();
