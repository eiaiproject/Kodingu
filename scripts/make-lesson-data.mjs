import { mkdir, readdir, readFile, unlink, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { courses } from '../assets/js/data/data.js';

const LESSON_DATA_DIR = new URL('../assets/js/data/lessons/', import.meta.url);

class RawSource {
  constructor(source) {
    this.source = source;
  }
}

function serialize(value, depth = 0) {
  const indent = '  '.repeat(depth);
  const childIndent = '  '.repeat(depth + 1);

  if (value instanceof RawSource) return value.source;
  if (typeof value === 'function') return value.toString();
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    return `[\n${value
      .map((item) => `${childIndent}${serialize(item, depth + 1)}`)
      .join(',\n')}\n${indent}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).filter(([, item]) => item !== undefined);
    if (!entries.length) return '{}';
    return `{\n${entries
      .map(([key, item]) => `${childIndent}${JSON.stringify(key)}: ${serialize(item, depth + 1)}`)
      .join(',\n')}\n${indent}}`;
  }
  return JSON.stringify(value);
}

function testSource(test) {
  return test.source ? `(${test.source})` : test.run.toString();
}

function serializeLesson(lesson) {
  const { tests, ...challenge } = lesson.challenge;
  return serialize({
    ...lesson,
    challenge: {
      ...challenge,
      tests: tests.map((test) => ({
        label: test.label,
        run: new RawSource(testSource(test))
      }))
    }
  });
}

function moduleSource(lesson) {
  return `// Generated by scripts/make-lesson-data.mjs from assets/js/data/data.js.\n// Do not edit by hand.\nimport * as dataHelpers from '../data-helpers.js';\n\nconst {\n  colorContrast,\n  cssHas,\n  cssIncludes,\n  cssOrder,\n  cssRule,\n  cssValue,\n  normalize,\n  parseColor,\n  parseCss,\n  parseJsonLd,\n  textOf,\n  textsOf\n} = dataHelpers;\n\nexport const lesson = ${serializeLesson(lesson)};\n`;
}

export function buildLessonData() {
  const modules = new Map();
  for (const course of courses) {
    for (const module of course.modules) {
      for (const lesson of module.lessons) {
        modules.set(`${lesson.id}.js`, moduleSource(lesson));
      }
    }
  }
  return modules;
}

export async function writeLessonModules() {
  const modules = buildLessonData();
  await mkdir(LESSON_DATA_DIR, { recursive: true });

  await Promise.all(
    [...modules].map(([name, source]) => writeFile(new URL(name, LESSON_DATA_DIR), source))
  );

  const existing = await readdir(LESSON_DATA_DIR);
  const removed = await Promise.all(
    existing
      .filter((name) => name.endsWith('.js') && !modules.has(name))
      .map(async (name) => {
        await unlink(new URL(name, LESSON_DATA_DIR));
        return name;
      })
  );

  console.log(`Wrote ${modules.size} lesson data modules to assets/js/data/lessons/`);
  if (removed.length) console.log(`Removed ${removed.length} orphaned lesson data module(s).`);
  return modules.size;
}

async function checkLessonModules() {
  const modules = buildLessonData();
  const existing = new Set(await readdir(LESSON_DATA_DIR));
  const problems = (
    await Promise.all(
      [...modules].map(async ([name, source]) => {
        try {
          const current = await readFile(new URL(name, LESSON_DATA_DIR), 'utf8');
          return current === source ? null : `stale ${name}`;
        } catch {
          return `missing ${name}`;
        }
      })
    )
  ).filter(Boolean);

  for (const name of existing) {
    if (name.endsWith('.js') && !modules.has(name)) problems.push(`orphaned ${name}`);
  }

  if (problems.length) {
    console.error(`Lesson data modules are out of date (${problems.length}):`);
    for (const problem of problems.slice(0, 20)) console.error(`  ${problem}`);
    if (problems.length > 20) console.error(`  and ${problems.length - 20} more`);
    process.exitCode = 1;
    return;
  }

  console.log(`Lesson data modules are up to date (${modules.size}).`);
}

async function run() {
  if (process.argv.includes('--check')) await checkLessonModules();
  else await writeLessonModules();
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  await run();
}
